test('sharing copies one saved revision, with an explicit project confirmation', async ({ page }) => {
  await open(page, 'artifacts/private')
  await page.getByRole('button', { name: 'Copy saved revision to project…' }).click()
  const dialog = page.getByRole('dialog')
  await dialog.getByRole('combobox', { name: 'Project', exact: true }).selectOption('neighborhood')
  await expect(dialog.getByRole('button', { name: 'Copy and share revision' })).toBeDisabled()
  await dialog.getByRole('checkbox').check()
  await dialog.getByRole('button', { name: 'Copy and share revision' }).click()
  await expect(dialog).toHaveCount(0)
  const [copy] = await writes(page, 'artifact-create')
  expect(copy.args.project).toBe('neighborhood')
  expect(copy.args.body).toBe('Private draft not intended for project members.')
  expect(copy.args.id).not.toBe('private')
  expect(await writes(page, 'artifact-save')).toHaveLength(0)
})

