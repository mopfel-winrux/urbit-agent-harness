test('one workspace watch serves the editor and its proposal query without a polling storm', async ({ page }) => {
  await page.clock.install()
  await open(page)
  await page.getByRole('button', { name: 'Proposals', exact: true }).click()
  await page.getByRole('button', { name: /A Saturday with the neighbors.*neighborhood-research/ }).click()
  const count = await page.evaluate(() => window.workFixture.calls.length)
  await page.clock.runFor(60_000)
  expect(await page.evaluate(() => window.workFixture.watchCount())).toBe(1)
  expect((await page.evaluate(() => window.workFixture.calls.length)) - count).toBeLessThanOrEqual(12)
})
