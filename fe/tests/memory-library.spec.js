test('a preference draft collapses, resumes and discards on mobile', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto(path)
  await inspect(page, 'project-review').click()
  const editor = page.getByRole('form', { name: 'Edit project-review' })
  const preference = editor.getByRole('checkbox', { name: /Use across topics/ })
  await preference.check()
  await inspect(page, 'project-review').click()
  await expect(editor).toBeHidden()
  await expect(inspect(page, 'project-review')).toHaveAttribute('aria-expanded', 'false')
  await expect(inspect(page, 'project-review')).toContainText('Unsaved changes')
  await inspect(page, 'project-review').click()
  await expect(preference).toBeChecked()
  await editor.getByRole('button', { name: 'Save memory', exact: true }).click()
  await inspect(page, 'project-review').click()
  await expect(preference).toBeChecked()
  await preference.uncheck()
  await editor.getByRole('button', { name: 'Close', exact: true }).click()
  await page.getByRole('button', { name: 'Discard changes', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Add memory', exact: true })).toBeEnabled()
  await inspect(page, 'project-review').click()
  await expect(preference).toBeChecked()
})
