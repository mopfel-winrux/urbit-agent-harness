test('ownership updates remain visible while peer edits are unsaved', async ({ page }) => {
  await page.goto('/apps/harness/tests/settings-fixture.html?page=peers')
  await page.locator('summary').filter({ hasText: '~nec' }).click()
  await page.getByRole('spinbutton', { name: 'Peer token limit for ~nec' }).fill('500')
  const owner = page.getByRole('combobox', { name: 'Owner ship', exact: true })
  await owner.fill('~nec'); await owner.press('Enter')
  await page.getByRole('button', { name: 'Save ownership' }).click()
  await expect(page.locator('summary').filter({ hasText: '~nec' })).toContainText('Owner · full admin')
  await expect(page.getByRole('spinbutton', { name: 'Peer token limit for ~nec' })).toHaveCount(0)
  await expect(page.locator('summary').filter({ hasText: '~bud' })).toHaveCount(0)
  await page.getByRole('button', { name: 'Save peer settings', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('reload before saving')
})

