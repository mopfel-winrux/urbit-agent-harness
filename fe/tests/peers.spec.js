for (const surface of ['peers', 'tlon']) test(`${surface} resets recorded usage without saving a draft limit`, async ({ page }) => {
  await page.goto(`/apps/harness/tests/settings-fixture.html?page=${surface}`)
  await page.locator('summary').filter({ hasText: '~nec' }).click()
  const limit = page.getByRole('spinbutton', { name: 'Peer token limit for ~nec' })
  await expect(page.getByText('1,234 tokens used', { exact: true })).toBeVisible()
  await limit.fill('9000')
  const reset = page.getByRole('button', { name: 'Reset token count for ~nec' })
  await reset.click()
  await expect(page.getByText('0 tokens used · Count reset.', { exact: true })).toBeVisible()
  await expect(reset).toBeDisabled()
  await expect(limit).toHaveValue('9000')
  await expect.poll(() => page.evaluate(() => window.settingsFixture.saves.map((action) => Object.keys(action)[0]))).toEqual(['peerReset'])
  await page.reload()
  await page.locator('summary').filter({ hasText: '~nec' }).click()
  await expect(page.getByText('0 tokens used', { exact: true })).toBeVisible()
  await expect(limit).toHaveValue('0')
})

