test('owners are full admins and optional sibling access survives reload', async ({ page }) => {
  await page.goto('/apps/harness/tests/settings-fixture.html?page=peers&moon')
  await expect(page.getByRole('heading', { name: 'Owner · full admin' })).toBeVisible()
  await page.locator('summary').filter({ hasText: '~bud' }).click()
  await expect(page.getByRole('spinbutton', { name: 'Peer token limit for ~bud' })).toHaveCount(0)
  const siblings = page.getByRole('checkbox', { name: /Make sibling moons full admins/ })
  await expect(siblings).not.toBeChecked()
  await siblings.check()
  await page.getByRole('button', { name: 'Save ownership' }).click()
  await expect(page.getByRole('status').filter({ hasText: 'Ownership saved.' })).toBeVisible()
  await page.reload()
  await expect(siblings).toBeChecked()
  await siblings.uncheck()
  await page.getByRole('button', { name: 'Clear owner', exact: true }).click()
  await page.getByRole('button', { name: 'Save ownership' }).click()
  await expect(page.getByRole('status').filter({ hasText: 'Ownership saved.' })).toBeVisible()
  await page.reload()
  await expect(page.getByRole('combobox', { name: 'Owner ship', exact: true })).toHaveValue('')
})

